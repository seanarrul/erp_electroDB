CREATE VIEW v_customer_receivables AS
SELECT 
    c.custNo,
    c.custName,
    c.address,
    c.payterm AS payTerms,
    COUNT(DISTINCT s.transNo) AS totalTransactions,
    COALESCE(SUM(ss.totalAmount), 0.0) AS totalBilled,
    COALESCE(SUM(ss.totalPaid), 0.0) AS totalCollected,
    COALESCE(SUM(ss.totalAmount - ss.totalPaid), 0.0) AS outstandingBalance,
    0 AS overdueCount
FROM CUSTOMER c
LEFT JOIN (
    SELECT 
        s.transNo,
        s.custNo,
        COALESCE(SUM(l.lineAmount), 0.0) AS totalAmount,
        COALESCE((SELECT SUM(amount) FROM PAYMENT WHERE transNo = s.transNo), 0.0) AS totalPaid
    FROM SALES s
    LEFT JOIN SALESDETAIL sd ON sd.transNo = s.transNo
    LEFT JOIN v_sale_lines l ON l.transNo = sd.transNo AND l.prodCode = sd.prodCode
    GROUP BY s.transNo, s.custNo
) ss ON ss.custNo = c.custNo
GROUP BY c.custNo, c.custName, c.address, c.payterm;


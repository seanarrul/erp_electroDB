ORDER BY p.payDate DESC, p.ORNo DESC;

CREATE VIEW v_employee_current_status AS
SELECT 
    e.empNo,
    e.lastName,
    e.firstName,
    e.firstName || ' ' || e.lastName AS fullName,
    e.gender,
    e.birthDate,
    e.hireDate,
    e.sepDate,
    CASE WHEN e.sepDate IS NULL THEN 'Active' ELSE 'Separated' END AS status,
    CASE WHEN e.sepDate IS NULL THEN 'Active' ELSE 'Separated' END AS employmentStatus,
    jh.deptCode,
    d.deptName,
    jh.jobCode,
    j.jobDesc,
    jh.salary,
    jh.salary AS currentSalary,
    jh.effDate AS currentJobEffDate,
    CAST((strftime('%Y', 'now') - strftime('%Y', e.hireDate)) AS INTEGER) AS yearsOfService
FROM EMPLOYEE e
LEFT JOIN (
    SELECT jh1.*
    FROM JOBHISTORY jh1
    JOIN (
        SELECT empNo, MAX(effDate) AS maxEffDate
        FROM JOBHISTORY
        GROUP BY empNo
    ) latest ON latest.empNo = jh1.empNo AND latest.maxEffDate = jh1.effDate
) jh ON jh.empNo = e.empNo
LEFT JOIN DEPARTMENT d ON d.deptCode = jh.deptCode
LEFT JOIN JOB j ON j.jobCode = jh.jobCode;

